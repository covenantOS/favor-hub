// Writes web/src/styles/layout.css from the style imports in src/layouts/App.astro, in the same order, so the React pages and the
// classic pages always read the same stylesheets with the same cascade. Runs before every build and in the tests.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const layout = readFileSync(here('../../src/layouts/App.astro'), 'utf8');
const files = [...layout.matchAll(/^import '\.\.\/styles\/([\w.-]+\.css)';/gm)].map((m) => m[1]);
if (files.length < 20) throw new Error('layout-css: found only ' + files.length + ' style imports in App.astro');
const out = ['/* Generated by web/scripts/layout-css.mjs from src/layouts/App.astro. Do not edit. */']
  .concat(files.map((f) => `@import '../../../src/styles/${f}';`))
  .concat(["@import '../../../app/src/styles/cmdk.css';", "@import '../../../app/src/styles/learn-panel.css';"])
  .join('\n') + '\n';
const target = here('../src/styles/layout.css');
let old = '';
try { old = readFileSync(target, 'utf8'); } catch { /* first run */ }
mkdirSync(here('../src/styles'), { recursive: true });
if (old !== out) writeFileSync(target, out);
console.log('layout-css: ' + files.length + ' stylesheets');
