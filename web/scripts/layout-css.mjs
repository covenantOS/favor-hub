// Writes web/src/styles/layout.css from the style imports in src/layouts/App.astro, in the same order, so the React pages and the
// classic pages always read the same stylesheets with the same cascade. Runs before every build and in the tests.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const layout = readFileSync(here('../../src/layouts/App.astro'), 'utf8');
const files = [...layout.matchAll(/^import '\.\.\/styles\/([\w.-]+\.css)';/gm)].map((m) => m[1]);
if (files.length < 20) throw new Error('layout-css: found only ' + files.length + ' style imports in App.astro');
const out = ['/* Generated by web/scripts/layout-css.mjs from src/layouts/App.astro. Do not edit. */']
  .concat(files.map((f) => `@import '../../../src/styles/${f}';`))
  .concat(["@import '../../../app/src/styles/cmdk.css';", "@import '../../../app/src/styles/learn-panel.css';", "@import '../../../app/src/styles/old-hub.css';"])
  .join('\n') + '\n';
const target = here('../src/styles/layout.css');
let old = '';
try { old = readFileSync(target, 'utf8'); } catch { /* first run */ }
mkdirSync(here('../src/styles'), { recursive: true });
if (old !== out) writeFileSync(target, out);
// The three scripts every page ran inline in its head (page ownership, Lite mode, held space) as one file: a repeat visit reads it from the
// cache instead of downloading the same 38 KB of text inside every page. Generated here from the classic layout's own sources.
const boot = ['hub-own.js', 'lite.js', 'hub-motion.js'].map((f) => readFileSync(here('../../public/js/' + f), 'utf8')).join('\n;\n');
mkdirSync(here('../src/boot'), { recursive: true });
let oldBoot = '';
try { oldBoot = readFileSync(here('../src/boot/favor-boot.js'), 'utf8'); } catch { /* first run */ }
if (oldBoot !== boot) writeFileSync(here('../src/boot/favor-boot.js'), boot);
console.log('layout-css: ' + files.length + ' stylesheets');
