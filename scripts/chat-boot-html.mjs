// Writes web/src/features/chat-page/bootHtml.ts: the classic Chat page's first paint (bootHtml in public/js/chat/chat-ui.js), so the web
// app's server can draw Chat's frame without running that script. tests/chat-web-skeleton.test.mjs fails when the two drift; run this
// script (node scripts/chat-boot-html.mjs) after changing the frame in chat-ui.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { createContext, runInContext } from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

export function classicBootHtml() {
  const ctx = { window: {}, document: {}, Intl, matchMedia: () => ({ matches: false }) };
  createContext(ctx);
  runInContext(readFileSync(root + 'public/js/chat/chat-ui.js', 'utf8'), ctx);
  return ctx.window.FavorChat.bootHtml();
}

export const BOOT_FILE = root + 'web/src/features/chat-page/bootHtml.ts';

export function bootFileSource(html) {
  return (
    '// Generated by scripts/chat-boot-html.mjs from public/js/chat/chat-ui.js (bootHtml). Do not edit by hand.\n' +
    "// Chat's first paint: channel list bones, an empty conversation and the message box, at the final size.\n" +
    'export const CHAT_BOOT_HTML = ' + JSON.stringify(html) + ';\n'
  );
}

if (process.argv.includes('--write')) {
  writeFileSync(BOOT_FILE, bootFileSource(classicBootHtml()));
  console.log('wrote', BOOT_FILE);
}
